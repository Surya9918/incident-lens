import { readFileSync, writeFileSync, mkdirSync } from 'node:fs';
import { makeIncident } from '../src/synthetic.js';
import { extractFeatures } from '../src/features.js';
import { predict, validateModel } from '../src/model.js';
import { analyze } from '../src/analyze.js';
const models = Object.fromEntries(['ranker', 'no-graph', 'metrics-learned'].map(n => [n, validateModel(JSON.parse(readFileSync(`models/${n}.json`, 'utf8')))]));
function evaluate(topology, start) {
  const results = Object.fromEntries(['metrics-threshold', ...Object.keys(models)].map(n => [n, { top1: 0, top3: 0, reciprocalRank: 0 }]));
  let detected = 0, cleanAlerts = 0; const delays = [], byFault = {};
  for (let i = 0; i < 120; i++) {
    const { incident, truth } = makeIncident(start + i, { topology });
    const records = extractFeatures(incident);
    const result = analyze(incident, models.ranker);
    if (result.detectedAt !== null) { detected++; delays.push(Math.max(0, result.detectedAt - truth.onset)); }
    for (const [name, values] of Object.entries(results)) {
      const ranking = name === 'metrics-threshold' ? predict(records, models.ranker, 'metrics') : predict(records, models[name]);
      const rank = ranking.findIndex(r => r.service === truth.rootCause) + 1;
      values.top1 += Number(rank === 1); values.top3 += Number(rank <= 3); values.reciprocalRank += 1 / rank;
      if (name === 'ranker') { byFault[truth.fault] ??= { count: 0, correct: 0 }; byFault[truth.fault].count++; byFault[truth.fault].correct += Number(rank === 1); }
    }
  }
  for (let i = 0; i < 60; i++) if (analyze(makeIncident(start + 1000 + i, { clean: true, topology }).incident, models.ranker).status !== 'no_anomaly') cleanAlerts++;
  for (const r of Object.values(results)) { r.top1 /= 120; r.top3 /= 120; r.reciprocalRank /= 120; }
  delays.sort((a, b) => a - b);
  return { topology, faultIncidents: 120, healthyWindows: 60, seedRange: [start, start + 119], results, byFault, detectionRecall: detected / 120, healthyFalsePositiveRate: cleanAlerts / 60, medianDetectionDelayMs: delays.length ? delays[Math.floor(delays.length / 2)] : null };
}
const report = { protocol: 'Frozen model; disjoint incident seeds; no per-row random splits; no held-out retraining.', limitations: 'Synthetic single-fault results only. Held-out topology is generated by the same simulator; this is not external validation or RCAEval performance.', trainingSeedRange: [1000, 1239], evaluations: [evaluate('shop', 10000), evaluate('chain', 20000)] };
if (process.argv.includes('--check')) {
  const expected = JSON.parse(readFileSync('docs/benchmark.json', 'utf8'));
  if (JSON.stringify(expected) !== JSON.stringify(report)) throw new Error('Benchmark drift: inspect changes, then regenerate the committed report');
  console.log('Benchmark reproduces the committed report exactly.');
} else {
  mkdirSync('docs', { recursive: true });
  writeFileSync('docs/benchmark.json', JSON.stringify(report, null, 2) + '\n');
}
console.table(report.evaluations.flatMap(e => Object.entries(e.results).map(([method, r]) => ({ topology: e.topology, method, top1: r.top1.toFixed(3), top3: r.top3.toFixed(3), mrr: r.reciprocalRank.toFixed(3) }))));
